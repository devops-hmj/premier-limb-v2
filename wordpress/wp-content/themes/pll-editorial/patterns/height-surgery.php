			<!-- wp:heading {"anchor":"how-height-surgery-works"} -->
			<h2 class="wp-block-heading" id="how-height-surgery-works">How Height Surgery Works</h2>
			<!-- /wp:heading -->

			<!-- wp:paragraph -->
			<p>Height surgery works in four phases: the surgery itself, a gradual lengthening period, a bone-hardening period, and eventual nail removal. The full process takes 6 to 12 months per bone segment.</p>
			<!-- /wp:paragraph -->

			<!-- wp:heading {"anchor":"the-surgery","level":3} -->
			<h3 class="wp-block-heading" id="the-surgery">The Surgery</h3>
			<!-- /wp:heading -->

			<!-- wp:paragraph -->
			<p>The surgeon makes a controlled cut in the bone, called an osteotomy, through small incisions, then inserts an internal telescopic nail into the marrow canal and secures it with screws. The procedure is performed under general anesthesia and typically takes 1 to 2 hours per bone. There is no external hardware after surgery. Most patients are discharged the same day but some stay one night in the hospital.</p>
			<!-- /wp:paragraph -->

			<!-- wp:heading {"anchor":"the-lengthening-phase","level":3} -->
			<h3 class="wp-block-heading" id="the-lengthening-phase">The Lengthening Phase</h3>
			<!-- /wp:heading -->

			<!-- wp:paragraph -->
			<p>Lengthening begins about 7 to 10 days after surgery. The patient holds an external remote control device against the skin, which activates the internal nail to extend approximately 1 millimeter per day, roughly 1 inch per month. As the two bone segments separate, the body grows new bone in the gap. This phase lasts 2 to 3 months and requires physical therapy throughout to keep muscles and joints flexible.</p>
			<!-- /wp:paragraph -->

