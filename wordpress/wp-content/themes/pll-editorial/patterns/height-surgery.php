			<!-- wp:heading {"anchor":"the-consolidation-phase","level":3} -->
			<h3 class="wp-block-heading" id="the-consolidation-phase">The Consolidation Phase</h3>
			<!-- /wp:heading -->

			<!-- wp:paragraph -->
			<p>Once the target height is reached, the new bone hardens over 3 to 6 months. Patients gradually return to full weight-bearing during this time. Most are walking without crutches within 3 to 4 months of finishing the lengthening phase.</p>
			<!-- /wp:paragraph -->

			<!-- wp:heading {"anchor":"nail-removal","level":3} -->
			<h3 class="wp-block-heading" id="nail-removal">Nail Removal</h3>
			<!-- /wp:heading -->

			<!-- wp:paragraph -->
			<p>The internal nail is usually removed 12 to 18 months after the original surgery in a short outpatient procedure. Removal is recommended, though some patients leave the nail in place if it causes no discomfort.</p>
			<!-- /wp:paragraph -->

			<!-- wp:heading {"anchor":"who-qualifies-for-height-surgery"} -->
			<h2 class="wp-block-heading" id="who-qualifies-for-height-surgery">Who Qualifies for Height Surgery</h2>
			<!-- /wp:heading -->

			<!-- wp:paragraph -->
			<p>Candidates are healthy individuals who have finished growing, confirmed by an X-ray showing closed growth plates. There is no minimum height requirement. Patients range from those who are clinically short to those of average height who want a meaningful change. The procedure is not appropriate for people with active infections, uncontrolled medical conditions, severe osteoporosis, or a history of smoking, which impairs bone healing. Only a consultation with the operating surgeon can confirm candidacy.</p>
