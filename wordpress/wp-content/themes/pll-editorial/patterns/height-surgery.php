			<p>The result is permanent. The new bone that forms during the procedure is your own natural bone, and once it hardens, it is as strong as the bone you were born with. The technique, distraction osteogenesis, has been used by orthopedic surgeons for decades to treat limb length discrepancies and reconstruct bone after trauma. What has changed is the hardware. Modern height surgery uses an internal telescopic nail placed entirely inside the bone, replacing the external metal frames that once defined the procedure.</p>
