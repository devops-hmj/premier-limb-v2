			<!-- wp:heading {"anchor":"risks-of-height-surgery"} -->
			<h2 class="wp-block-heading" id="risks-of-height-surgery">Risks of Height Surgery</h2>
			<!-- /wp:heading -->

			<!-- wp:paragraph -->
			<p>Height surgery is major surgery, and complications are possible. The most common are joint stiffness, muscle tightness during lengthening, and slower-than-expected bone healing, all typically managed with physical therapy and monitoring. Less common but more serious risks include nerve injury, infection, and hardware failure. Risk rises with greater lengthening distances, which is why experienced surgeons recommend conservative targets of 2 to 3 inches per bone. For the complete picture of benefits weighed against risks, see <a href="/limb-lengthening-what-you-gain-what-you-risk/">what you gain and what you risk</a>.</p>
			<!-- /wp:paragraph -->

			<!-- wp:paragraph -->
			<p>The single most important way to reduce risk is surgeon selection. A surgeon with fellowship training in orthopedic trauma has managed hundreds of complex bone injuries and reconstructions before performing a cosmetic case, which is exactly the depth of experience needed if a complication arises.</p>
